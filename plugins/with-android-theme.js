const { promises: fs } = require('fs');
const path = require('path');
const {
  AndroidConfig,
  withAndroidColors,
  withAndroidColorsNight,
  withAndroidStyles,
  withDangerousMod,
} = require('expo/config-plugins');

// Expo's generated Android theme only sets colorPrimary, so every native
// widget the JS never paints — the Switch thumb, Alert dialogs (background,
// title, buttons), text-selection handles — falls back to AppCompat's stock
// teal accent on a square grey panel, in both light and dark. This plugin
// puts the app palette into the native theme instead. The values mirror
// src/constants/theme.ts (a jest test keeps them in step); day/night pairs
// go to values/ and values-night/ so the system follows the same scheme the
// JS side renders (Appearance.setColorScheme drives AppCompat's night mode).
const PALETTE = {
  light: { tint: '#1E6BE0', surface: '#FFFFFF', text: '#0B1424', textSecondary: '#5A6A7E' },
  dark: { tint: '#4E9BF5', surface: '#101D34', text: '#F2F6FB', textSecondary: '#8FA2BB' },
};

const COLOR_NAMES = {
  tint: 'flyrightTint',
  surface: 'flyrightSurface',
  text: 'flyrightText',
  textSecondary: 'flyrightTextSecondary',
};

const DIALOG_STYLE = 'Theme.App.Dialog';
const DIALOG_DRAWABLE = 'flyright_dialog_background';

// The same inset-and-shape recipe as AppCompat's abc_dialog_material_background,
// on the app surface colour with the cards' corner radius.
const DIALOG_BACKGROUND_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-theme.js -->
<inset xmlns:android="http://schemas.android.com/apk/res/android"
    android:insetLeft="16dp"
    android:insetTop="16dp"
    android:insetRight="16dp"
    android:insetBottom="16dp">
  <shape android:shape="rectangle">
    <solid android:color="@color/${COLOR_NAMES.surface}" />
    <corners android:radius="20dp" />
  </shape>
</inset>
`;

function assignColors(xml, scheme) {
  let out = xml;
  for (const [key, name] of Object.entries(COLOR_NAMES)) {
    out = AndroidConfig.Colors.assignColorValue(out, { name, value: PALETTE[scheme][key] });
  }
  // Expo's default colorPrimary is an unrelated navy; make it the tint too.
  return AndroidConfig.Colors.assignColorValue(out, {
    name: 'colorPrimary',
    value: PALETTE[scheme].tint,
  });
}

function withAppThemeStyles(config) {
  return withAndroidStyles(config, (config) => {
    const parent = AndroidConfig.Styles.getAppThemeGroup();
    const appThemeItems = {
      colorAccent: `@color/${COLOR_NAMES.tint}`,
      // Both attrs: RN's Alert picks AppCompat's dialog when the activity is
      // AppCompat (it is) and the framework one otherwise.
      alertDialogTheme: `@style/${DIALOG_STYLE}`,
      'android:alertDialogTheme': `@style/${DIALOG_STYLE}`,
    };
    for (const [name, value] of Object.entries(appThemeItems)) {
      config.modResults = AndroidConfig.Styles.assignStylesValue(config.modResults, {
        add: true,
        parent,
        name,
        value,
      });
    }

    const styles = config.modResults.resources.style ?? [];
    config.modResults.resources.style = styles.filter((s) => s.$.name !== DIALOG_STYLE);
    config.modResults.resources.style.push({
      $: { name: DIALOG_STYLE, parent: 'ThemeOverlay.AppCompat.Dialog.Alert' },
      item: [
        { _: `@color/${COLOR_NAMES.tint}`, $: { name: 'colorAccent' } },
        { _: `@drawable/${DIALOG_DRAWABLE}`, $: { name: 'android:windowBackground' } },
        { _: `@color/${COLOR_NAMES.text}`, $: { name: 'android:textColorPrimary' } },
        { _: `@color/${COLOR_NAMES.textSecondary}`, $: { name: 'android:textColorSecondary' } },
      ],
    });
    return config;
  });
}

function withDialogBackgroundDrawable(config) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const dir = path.join(
        config.modRequest.platformProjectRoot,
        'app/src/main/res/drawable',
      );
      await fs.mkdir(dir, { recursive: true });
      await fs.writeFile(path.join(dir, `${DIALOG_DRAWABLE}.xml`), DIALOG_BACKGROUND_XML);
      return config;
    },
  ]);
}

module.exports = function withAndroidTheme(config) {
  config = withAndroidColors(config, (config) => {
    config.modResults = assignColors(config.modResults, 'light');
    return config;
  });
  config = withAndroidColorsNight(config, (config) => {
    config.modResults = assignColors(config.modResults, 'dark');
    return config;
  });
  config = withAppThemeStyles(config);
  return withDialogBackgroundDrawable(config);
};

module.exports.PALETTE = PALETTE;
